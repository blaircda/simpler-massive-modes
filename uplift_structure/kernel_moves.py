"""
Item 8 (second half): the uplift kernel is generated by Euler-class moves.

e = sum_k (-1)^k Lambda^k(10) restricts to zero on Spin(9).  For a D5
class nu, the conjugation-merged move e (x) V_nu is even iff l5(nu) = 0.
Define h_nu = e V_nu / 2 (l5 = 0) or e V_nu (l5 > 0).

Per level n = 6..KMAX:
 * the h_nu supported inside the admissible candidates are linearly
   independent, their number equals the kernel dimension, and they
   generate the full integer kernel of the restriction map;
 * for n <= 10 (stored enumeration), every uplift is written uniquely as
   canonical + sum_nu t_nu h_nu; the ranges of t_nu are reported, together
   with whether all t_nu >= 0 (canonical at the corner of an orthant).
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import DATA, R9, canonical, load_R10

from sage.all import WeylCharacterRing, ZZ, matrix, vector
from uplift import candidates, interlacing, restrict
from weights import dynkin_D5

KMAX = 16
D5 = WeylCharacterRing("D5", style="coroots")
_V = D5(1, 0, 0, 0, 0)
EULER = sum((-1) ** k * _V.exterior_power(k) for k in range(11))


def merged(char):
    """Sage D5 character -> {conjugation class (l5 >= 0, doubled): coeff}."""
    out = {}
    for hw, k in char.monomial_coefficients().items():
        v = [int(2 * x) for x in hw.to_vector()]
        lam = (v[0], v[1], v[2], v[3], abs(v[4]))
        out[lam] = out.get(lam, 0) + k
    return {l: k for l, k in out.items() if k}


_cache = {}


def move(nu):
    if nu not in _cache:
        _cache[nu] = merged(EULER * D5(*dynkin_D5(nu)))
    return _cache[nu]


def d5_classes(l1max):
    for l1 in range(l1max + 1):
        for l2 in range(l1 + 1):
            for l3 in range(l2 + 1):
                for l4 in range(l3 + 1):
                    for l5 in range(l4 + 1):
                        nu = (l1, l2, l3, l4, l5)
                        if len({x % 2 for x in nu}) == 1:
                            yield nu


def main():
    assert EULER.degree() == 0
    print("e (merged) =", move((0, 0, 0, 0, 0)))
    for nu in [(0, 0, 0, 0, 0), (2, 2, 0, 0, 0), (1, 1, 1, 1, 1)]:
        assert restrict(move(nu)) == {}, "Euler move does not restrict to zero"

    L = load_R10()
    with open(os.path.join(DATA, "R10_all_uplifts.json")) as fh:
        allu = json.load(fh)["levels"]

    for n in range(6, KMAX + 1):
        m = R9(L, n)
        cands = candidates(m)
        cs = set(cands)
        idx = {l: j for j, l in enumerate(cands)}
        H, NU = [], []
        for nu in d5_classes(max(l[0] for l in cands)):
            mv = move(nu)
            if mv and set(mv) <= cs:
                even = all(k % 2 == 0 for k in mv.values())
                assert even == (nu[4] == 0), f"evenness not tied to l5 = 0 at nu = {nu}"
                H.append({l: (k // 2 if even else k) for l, k in mv.items()})
                NU.append(nu)
        Hm = matrix(ZZ, len(H), len(cands),
                    {(i, idx[l]): k for i, h in enumerate(H) for l, k in h.items()}, sparse=True)
        mus = sorted(m)
        midx = {mu: i for i, mu in enumerate(mus)}
        A = matrix(ZZ, len(mus), len(cands),
                   {(midx[mu], j): 1 for j, l in enumerate(cands) for mu in interlacing(l)},
                   sparse=True)
        K = A.right_kernel()
        assert Hm.rank() == len(H) == K.rank(), f"moves do not form a basis at level {n}"
        assert Hm.row_module(ZZ).index_in(K) == 1, f"moves do not generate integer kernel at {n}"
        line = (f"n={n:2d} kernel dim={K.rank():3d} = #moves ({sum(v[4] == 0 for v in NU)} halved), "
                f"generate integer kernel")

        if str(n) in allu:
            rec = allu[str(n)]
            classes = [tuple(c) for c in rec["classes_ambient2"]]
            can = canonical(L, n)
            cvec = vector(ZZ, [can.get(l, 0) for l in cands])
            T = []
            for vec in rec["uplifts"]:
                s = {l: k for l, k in zip(classes, vec) if k}
                d = vector(ZZ, [s.get(l, 0) for l in cands]) - cvec
                t = Hm.transpose().solve_right(d)
                assert all(x in ZZ for x in t)
                T.append(t)
            rng = [(min(t[i] for t in T), max(t[i] for t in T)) for i in range(len(H))]
            corner = all(lo >= 0 for lo, _ in rng)
            line += f" | {len(T)} uplifts, canonical at orthant corner: {corner}"
            print(line, flush=True)
            for nu, (lo, hi) in zip(NU, rng):
                print(f"    nu={nu} dynkin={dynkin_D5(nu)}  t in [{lo}, {hi}]")
            if not corner:
                neg = sum(1 for t in T if min(t) < 0)
                print(f"    {neg} uplifts have a negative coordinate")
        else:
            print(line, flush=True)


if __name__ == "__main__":
    main()
