# ------------------------------------------------------------------------------
# Example: Constructing the SO(10) Character at Level n in SageMath
# ------------------------------------------------------------------------------
def get_so10_character(level):
    """Returns the total D5 character at a given level using coroots."""
    char = D5(0)
    for mult, dim, coroots in SO10_SUPERMULTIPLETS_DYNKIN[level]["bosons"]:
        irrep = D5(*coroots)
        assert irrep.degree() == dim, f"Dimension mismatch: {irrep.degree()} != {dim}"
        char += mult * irrep
    for mult, dim, coroots in SO10_SUPERMULTIPLETS_DYNKIN[level]["fermions"]:
        irrep = D5(*coroots)
        assert irrep.degree() == dim, f"Dimension mismatch: {irrep.degree()} != {dim}"
        char += mult * irrep
    return char
